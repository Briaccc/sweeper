const LANG = document.documentElement.getAttribute('lang') === 'en' ? 'en' : 'fr';
const LOCALE = LANG === 'fr' ? 'fr-FR' : 'en-US';

function t(text, vars) {
  let out = LANG === 'en' && Object.prototype.hasOwnProperty.call(I18N_EN, text) ? I18N_EN[text] : text;
  if (vars) out = out.replace(/\{(\w+)\}/g, (all, key) => (key in vars ? String(vars[key]) : all));
  return out;
}

/** Translate the static text and the title/placeholder/aria-label attributes. */
function translatePage(root = document.body) {
  if (LANG === 'fr') return;
  const known = key => Object.prototype.hasOwnProperty.call(I18N_EN, key);
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes = [];
  while (walker.nextNode()) nodes.push(walker.currentNode);
  for (const node of nodes) {
    const raw = node.nodeValue;
    const key = raw.replace(/\s+/g, ' ').trim();
    if (!key || !known(key)) continue;
    // keep one space where the source had spacing, so inline text stays apart
    node.nodeValue = (/^\s/.test(raw) ? ' ' : '') + I18N_EN[key] + (/\s$/.test(raw) ? ' ' : '');
  }
  for (const node of root.querySelectorAll('[title],[placeholder],[aria-label]')) {
    for (const attr of ['title', 'placeholder', 'aria-label']) {
      const key = (node.getAttribute(attr) || '').replace(/\s+/g, ' ').trim();
      if (key && known(key)) node.setAttribute(attr, I18N_EN[key]);
    }
  }
  document.title = t(document.title);
}
